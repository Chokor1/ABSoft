const STORAGE_KEY = 'absoft-lang';

function detect() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && DICT[saved]) return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export let lang = detect();
export const dir = () => (lang === 'ar' ? 'rtl' : 'ltr');
export const isRtl = () => lang === 'ar';

/**
 * Arabic month names with Latin digits — business users read prices and dates
 * in Western numerals even when the interface is Arabic.
 */
export const locale = () => (lang === 'ar' ? 'ar-u-nu-latn' : undefined);

export function t(key, params) {
  const table = DICT[lang] || DICT.en;
  let text = table[key] ?? DICT.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, v);
  }
  return text;
}

/** Plural-aware count helper: `count('exp', 3)` → 'exp.count' or 'exp.count_one'. */
export const count = (prefix, n) => t(n === 1 ? `${prefix}.count_one` : `${prefix}.count`, { n });

export function setLang(next) {
  if (!DICT[next]) return;
  lang = next;
  localStorage.setItem(STORAGE_KEY, next);
  applyDocumentLang();
}

export function applyDocumentLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = dir();
}

/** Translate an error thrown by api.js, falling back to the server's own text. */
export function errorText(err) {
  if (!err) return t('err.unknown');
  if (err.code) {
    const params = { ...(err.params || {}) };
    if (params.field) params.field = t(`field.${params.field}`);
    const key = `err.${err.code}`;
    const translated = t(key, params);
    if (translated !== key) return translated;
  }
  return err.message || t('err.unknown');
}

